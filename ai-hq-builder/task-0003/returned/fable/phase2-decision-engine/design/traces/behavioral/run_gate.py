# Exercised through the real mechanism by `run_composition.py` — recorded here so
# the two lists together are exhaustive over the D-B8 layers.
EXERCISED_BY_COMPOSITION_SUITE = [
    "PC-1 priority within domain/output", "PC-2 equal-priority fail-closed",
    "PC-3 exception vs floor (DAT render floor substituted for the table's "
    "untrusted-quarantine floor — same mechanism, different governed output)",
    "PC-4 effective-window filtering",
    "PC-6 exception vs exception_authority=none",
    "PC-7 cross-domain conjunction (attention substituted as the third domain)",
    "PC-9 floor intersection", "PC-10 output ownership refusal",
    "PC-11 exception replaces only its target",
    "D-B8 §2 scope", "D-B8 §2 applicability_predicate",
]

# RW-23 — PC-12 belonged to neither list. It is mechanically PC-2's shape (an
# equal-priority contradiction failing closed) and is exercised FIXTURE-SIDE through
# A4's policy-version dispute, so it is accounted here rather than duplicated as a
# synthetic case or left unmentioned.
ACCOUNTED_ELSEWHERE = [
    "PC-12 — mechanically PC-2's shape; exercised fixture-side via A4's "
    "policy-version dispute, not duplicated in the composition suite.",
]


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixtures", default=DEFAULT_FIXTURES)
    ap.add_argument("--out", default="out")
    args = ap.parse_args(argv)

    base = run_all.run(args.fixtures, args.out)
    defects = run_defects.run(args.fixtures, args.out)
    shuffle = run_shuffle.run(args.fixtures, args.out)
    p2s05 = run_p2s05.run(args.out)
    p2s07 = run_p2s07.run(args.out)
    comp = run_composition.run(args.out)
    anti = [check_anticircularity.check_textual(),
            check_anticircularity.check_imports(),
            check_anticircularity.check_structural()]
    anti_ok = all(a["passed"] for a in anti)
    # RW-24 hygiene: this output belongs to the run's `--out` like every other. It
    # used to be written only by the standalone runner, into a fixed directory, so
    # `run_gate.py --out DIR` produced nine of the ten declared outputs and the
    # determinism comparison never covered it.
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "anticircularity.json"), "w",
              encoding="utf-8", newline="\n") as fh:
        json.dump({"passed": anti_ok, "checks": anti}, fh, indent=2,
                  sort_keys=True, ensure_ascii=False)
        fh.write("\n")

    s = base["summary"]
    e2e = next((r for r in base["results"] if r["fixture"] == "E2E-1"), {})
    e2e_extras = e2e.get("extras", {}) if isinstance(e2e, dict) else {}
    e2e_defect = next((d for d in defects["defects"]
                       if d["defect"] == "normalizer-authority-leak"), {})

    reach = defects.get("predicate_reachability", {})
    reachable = sum(1 for r in reach.values() if r.get("defect_reachable"))
    not_evaluable = [p for p, r in reach.items() if not r.get("defect_reachable")]
    p2s05_discriminating = p2s05["summary"].get("discriminating", 0)

    criteria = [
        ("1  anti-circularity: no oracle read in engine/scenario code",
         anti_ok, "textual+import+structural all pass"),
        ("2  all 27 x 3 = 81 combinations computed, none skipped",
         s["combinations_computed"] == 81 and s["unclassifiable"] == 0,
         "%d/81 computed, %d unclassifiable" % (s["combinations_computed"],
                                                s["unclassifiable"])),
        ("3  computed-vs-expected compared; every forbidden list evaluated",
         s["failures"] == 0 and not not_evaluable,
         "%d predicate evaluations over %d distinct predicates, %d defect-reachable, "
         "%d NOT-EVALUABLE (excluded from counts), %d judged failures"
         % (s["forbidden_predicates_evaluated"], len(reach), reachable,
            len(not_evaluable), s["failures"])),
        ("4  executed/verified only with an external receipt reference",
         all(not r["receipt_violations"] for r in base["results"]),
         "0 receipt-ownership violations across 81"),
        ("5  fold replays the multi-store basis with P2S-06 ordering",
         shuffle["summary"]["violations"] == 0,
         "%d combinations, %d order-invariant"
         % (shuffle["summary"]["combinations"], shuffle["summary"]["invariant"])),
        ("6  candidate-specific divergences produced, not assumed away",
         s["divergences"] > 0, "%d divergences computed" % s["divergences"]),
        ("7  E2E-1 executed as a real two-normalizer computation",
         bool(e2e_extras.get("authority_invariant")) and
         bool(e2e_extras.get("risk_suggestions_differ")) and
         bool(e2e_defect.get("effective")),
         "M1/M2 risk differ=%s, authority invariant=%s, seeded leak detected=%s"
         % (e2e_extras.get("risk_suggestions_differ"),
            e2e_extras.get("authority_invariant"), e2e_defect.get("effective"))),
        ("8  every seeded defect flips its target from pass to fail",
         bool(defects["summary"]["all_effective"]),
         "%d/%d named defect classes effective" % (defects["summary"]["defects_effective"],
                                                   defects["summary"]["defects_seeded"])),
        ("8b every forbidden predicate is provably able to fire",
         not not_evaluable,
         "%d/%d defect-reachable via a %d-mutation catalogue"
         % (reachable, len(reach), defects["summary"]["mutations_in_catalogue"])),
        ("9  shuffle-invariance across >=3 seeded permutations",
         shuffle["summary"]["permutations_per_combination"] >= 4
         and shuffle["summary"]["violations"] == 0,
         "%d permutations per combination, 0 violations"
         % shuffle["summary"]["permutations_per_combination"]),
        ("10 P2S-05 five traces present, computed, and discriminating",
         p2s05["summary"]["traces"] == 5 and p2s05["summary"]["failed"] == 0
         and p2s05_discriminating == 5,
         "%d/5 pass, %d/5 flip under a seeded defect (no literal verdicts)"
         % (p2s05["summary"]["passed"], p2s05_discriminating)),
        ("11 P2S-07 negative and positive tests present and reported",
         p2s07["summary"]["tests"] == 2 and p2s07["summary"]["failed"] == 0,
         "%d/2 tests pass" % p2s07["summary"]["passed"]),
        ("12 D-B8 composition layers exercised through the real mechanism",
         comp["summary"]["failed"] == 0
         and comp["summary"]["discriminating"] == comp["summary"]["cases"],
         "%d/%d cases pass, %d/%d flip under a composition-path defect"
         % (comp["summary"]["passed"], comp["summary"]["cases"],
            comp["summary"]["discriminating"], comp["summary"]["cases"])),
        # RW-21 — the judge's own checks are evidence only if they can fail, and a
        # declared defect switch that no runner seeds is a claim with nothing behind
        # it. Both are gated now, not merely reported.
        ("13 judge checks flippable; no orphaned switch, no dead mutation",
         defects["summary"]["judge_checks_not_falsifiable"] == 0
         and not defects["summary"]["orphaned_defect_switches"]
         and not defects["summary"]["mutations_witnessing_nothing"],
         "%d/%d judge checks have a named witness; %d never selected by any pass "
         "rule, %d selected but vacuous; orphaned switches: %s; mutations "
         "witnessing nothing: %s"
         % (defects["summary"]["judge_checks_falsifiable"],
            defects["summary"]["judge_checks_total"],
            len(defects["summary"]["pass_rule_checks_never_selected"]),
            len(defects["summary"]["pass_rule_checks_selected_but_vacuous"]),
            ", ".join(defects["summary"]["orphaned_defect_switches"]) or "none",
            ", ".join(defects["summary"]["mutations_witnessing_nothing"]) or "none")),
        # RW-19 — the D-B5 rule has no discriminating fixture; the self-test is the
        # only place it is shown load-bearing, so the gate depends on it.
        ("14 D-B5 degradation rule shown load-bearing (harness self-test)",
         bool(defects["summary"]["degradation_self_test_discriminates"]),
         "clean refuses citing degradation under an envelope that would otherwise "
         "authorize; seeded ignore_degradation emits the action"),
        # RW-27 — requirement 4's last uncompared dimension. The criterion is
        # coverage-honest, not count-maximising: it passes when every mapped
        # expectation is compared and agrees, and it PRINTS the unmapped and
        # unresolved counts so neither can hide inside a green line.
        ("15 expected.attention compared for every mapped fixture",
         base["summary"]["attention_compared"] > 0 and s["failures"] == 0,
         "%d/%d combinations compared, %d unmapped (expectation names no D-B7 §2.1 "
         "band), %d UNRESOLVED and raised as change requests (%s)"
         % (base["summary"]["attention_compared"], s["combinations_computed"],
            base["summary"]["attention_unmapped"],
            base["summary"]["attention_unresolved"],
            ", ".join(base["summary"]["attention_unresolved_fixtures"]) or "none")),
    ]

    print("=" * 86)
    print("TASK-0003 — P2S-01 Behavioral Candidate-Transition/Fold Simulator")
    print("=" * 86)
    print("fixtures %d x shapes %d (%s) = %d combinations"
          % (s["fixtures"], s["shapes"], ", ".join(SHAPES), s["combinations_expected"]))
    print()
    print("ACCEPTANCE CRITERIA")
    for label, ok, detail in criteria:
        print("  [%s] %-58s %s" % ("PASS" if ok else "FAIL", label, detail))

    print()
    print("EXERCISED through the real mechanism (run_composition.py)")
    print("  %s" % "; ".join(EXERCISED_BY_COMPOSITION_SUITE))
    print()
    print("ACCOUNTED ELSEWHERE (RW-23 — neither driven here nor unlisted)")
    for line in ACCOUNTED_ELSEWHERE:
        print("  - %s" % line)
    print()
    print("DECLARED NOT-SIMULATED (RW-09/RW-13 — these are NOT exercised)")
    for line in NOT_SIMULATED:
        print("  - %s" % line)

    all_ok = all(ok for _, ok, _ in criteria)
    payload = {
        "criteria": [{"criterion": c, "passed": bool(ok), "detail": d}
                     for c, ok, d in criteria],
        "all_passed": all_ok,
        "base_summary": s,
        "defects_summary": defects["summary"],
        "shuffle_summary": shuffle["summary"],
        "p2s05_summary": p2s05["summary"],
        "p2s07_summary": p2s07["summary"],
        "anticircularity_passed": anti_ok,
        "not_simulated": NOT_SIMULATED,
        "exercised_by_composition_suite": EXERCISED_BY_COMPOSITION_SUITE,
        "accounted_elsewhere": ACCOUNTED_ELSEWHERE,
        "composition_summary": comp["summary"],
        "predicates_not_evaluable": sorted(not_evaluable),
    }
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "gate_report.json"), "w",
              encoding="utf-8", newline="\n") as fh:
        json.dump(payload, fh, indent=2, sort_keys=True, ensure_ascii=False)
        fh.write("\n")

    print()
    print("GATE %s" % ("PASS — all acceptance criteria met" if all_ok
                       else "FAIL — see criteria above"))
    print("outputs written to %s/" % args.out)
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
