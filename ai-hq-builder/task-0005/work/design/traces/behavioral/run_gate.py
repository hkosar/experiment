def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixtures", default=DEFAULT_FIXTURES)
    ap.add_argument("--out", default="out")
    args = ap.parse_args(argv)

    base = run_all.run(args.fixtures, args.out)
    defects = run_defects.run(args.fixtures, args.out)
    shuffle = run_shuffle.run(args.fixtures, args.out)
    p2s05 = run_p2s05.run(args.out)
    p2s07 = run_p2s07.run(args.out)
    comp = run_composition.run(args.out)
    omut = run_oracle_mutations.run(args.fixtures, args.out)
    basis = run_basis.run(args.fixtures, args.out)
    sched = run_p2s04.run(args.out)
    # The stimulus-enumeration registry guard (closure finding M-1) belongs in the
    # gate, not only in the standalone runner: it was added to
    # `check_anticircularity.main()` first and this list was not updated, so the
    # guard ran when invoked directly and not when the gate ran. Caught by the
    # record-vs-file re-check, which is what that re-check is for.
    anti = [check_anticircularity.check_textual(),
            check_anticircularity.check_imports(),
            check_anticircularity.check_structural(),
            check_anticircularity.check_stimulus_enumeration()]
    anti_ok = all(a["passed"] for a in anti)
    # RW-24 hygiene: this output belongs to the run's `--out` like every other. It
    # used to be written only by the standalone runner, into a fixed directory, so
    # `run_gate.py --out DIR` produced nine of the ten declared outputs and the
    # determinism comparison never covered it.
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "anticircularity.json"), "w",
              encoding="utf-8", newline="\n") as fh:
        json.dump({"passed": anti_ok, "checks": anti}, fh, indent=2,
                  sort_keys=True, ensure_ascii=False)
        fh.write("\n")

    s = base["summary"]
    e2e = next((r for r in base["results"] if r["fixture"] == "E2E-1"), {})
    e2e_extras = e2e.get("extras", {}) if isinstance(e2e, dict) else {}
    e2e_defect = next((d for d in defects["defects"]
                       if d["defect"] == "normalizer-authority-leak"), {})

    reach = defects.get("predicate_reachability", {})
    reachable = sum(1 for r in reach.values() if r.get("defect_reachable"))
    not_evaluable = [p for p, r in reach.items() if not r.get("defect_reachable")]
    p2s05_discriminating = p2s05["summary"].get("discriminating", 0)

    criteria = [
        ("1  anti-circularity + Builder-added-stimulus registry",
         anti_ok,
         "textual+import+structural pass; stimulus enumeration %d pair(s) in use, "
         "%d unenumerated"
         % (len(anti[3]["pairs_in_use"]), len(anti[3]["unenumerated"]))),
        ("2  all 27 x 3 = 81 combinations computed, none skipped",
         s["combinations_computed"] == 81 and s["unclassifiable"] == 0,
         "%d/81 computed, %d unclassifiable" % (s["combinations_computed"],
                                                s["unclassifiable"])),
        ("3  computed-vs-expected compared; every forbidden list evaluated",
         s["failures"] == 0 and not not_evaluable,
         "%d predicate evaluations over %d distinct predicates, %d defect-reachable, "
         "%d NOT-EVALUABLE (excluded from counts), %d judged failures"
         % (s["forbidden_predicates_evaluated"], len(reach), reachable,
            len(not_evaluable), s["failures"])),
        ("4  executed/verified only with an external receipt reference",
         all(not r["receipt_violations"] for r in base["results"]),
         "0 receipt-ownership violations across 81"),
        ("5  fold replays the multi-store basis with P2S-06 ordering",
         shuffle["summary"]["violations"] == 0,
         "%d combinations, %d order-invariant"
         % (shuffle["summary"]["combinations"], shuffle["summary"]["invariant"])),
        ("6  candidate-specific divergences produced, not assumed away",
         s["divergences"] > 0, "%d divergences computed" % s["divergences"]),
        ("7  E2E-1 executed as a real two-normalizer computation",
         bool(e2e_extras.get("authority_invariant")) and
         bool(e2e_extras.get("risk_suggestions_differ")) and
         bool(e2e_defect.get("effective")),
         "M1/M2 risk differ=%s, authority invariant=%s, seeded leak detected=%s"
         % (e2e_extras.get("risk_suggestions_differ"),
            e2e_extras.get("authority_invariant"), e2e_defect.get("effective"))),
        ("8  every seeded defect flips its target from pass to fail",
         bool(defects["summary"]["all_effective"]),
         "%d/%d named defect classes effective" % (defects["summary"]["defects_effective"],
                                                   defects["summary"]["defects_seeded"])),
        ("8b every forbidden predicate is provably able to fire",
         not not_evaluable,
         "%d/%d defect-reachable via a %d-mutation catalogue"
         % (reachable, len(reach), defects["summary"]["mutations_in_catalogue"])),
        ("9  shuffle-invariance across >=3 seeded permutations",
         shuffle["summary"]["permutations_per_combination"] >= 4
         and shuffle["summary"]["violations"] == 0,
         "%d permutations per combination, 0 violations"
         % shuffle["summary"]["permutations_per_combination"]),
        ("10 P2S-05 five traces present, computed, and discriminating",
         p2s05["summary"]["traces"] == 5 and p2s05["summary"]["failed"] == 0
         and p2s05_discriminating == 5,
         "%d/5 pass, %d/5 flip under a seeded defect (no literal verdicts)"
         % (p2s05["summary"]["passed"], p2s05_discriminating)),
        ("11 P2S-07 negative and positive tests present and reported",
         p2s07["summary"]["tests"] == 2 and p2s07["summary"]["failed"] == 0,
         "%d/2 tests pass" % p2s07["summary"]["passed"]),
        ("12 D-B8 composition layers exercised through the real mechanism",
         comp["summary"]["failed"] == 0
         and comp["summary"]["discriminating"] == comp["summary"]["cases"],
         "%d/%d cases pass, %d/%d flip under a composition-path defect"
         % (comp["summary"]["passed"], comp["summary"]["cases"],
            comp["summary"]["discriminating"], comp["summary"]["cases"])),
        # RW-21 — the judge's own checks are evidence only if they can fail, and a
        # declared defect switch that no runner seeds is a claim with nothing behind
        # it. Both are gated now, not merely reported.
        # P2U-01 added `mapped_dimensions_have_comparators`, a judge check no engine
        # defect can flip because it reads only the ORACLE side. Layer D reported it
        # NOT-FALSIFIABLE, correctly — layer D perturbs the engine. Rather than
        # exempting it, `run_defects.ORACLE_SIDE_JUDGE_CHECKS` declares where its
        # witness lives, and the gate resolves that pointer here: the named key in the
        # oracle-mutation summary must be true. A declaration whose witness has gone
        # quiet fails this criterion instead of being a comment nobody re-reads.
        ("13 judge checks flippable; no orphaned switch, no dead mutation",
         defects["summary"]["judge_checks_not_falsifiable"] == 0
         and not defects["summary"]["judge_checks_oracle_side_stale"]
         and not defects["summary"]["judge_checks_oracle_side_absent"]
         and all(bool(omut["summary"].get(
             run_defects.ORACLE_SIDE_JUDGE_CHECKS[c]["witness_key"]))
             for c in defects["summary"]["judge_checks_oracle_side"])
         and not defects["summary"]["orphaned_defect_switches"]
         and not defects["summary"]["mutations_witnessing_nothing"],
         "%d/%d judge checks have a named witness; %d oracle-side (%s), each "
         "witnessed in run_oracle_mutations and resolved here; %d never selected by "
         "any pass rule, %d selected but vacuous; orphaned switches: %s; mutations "
         "witnessing nothing: %s"
         % (defects["summary"]["judge_checks_falsifiable"],
            defects["summary"]["judge_checks_total"],
            len(defects["summary"]["judge_checks_oracle_side"]),
            ", ".join(defects["summary"]["judge_checks_oracle_side"]) or "none",
            len(defects["summary"]["pass_rule_checks_never_selected"]),
            len(defects["summary"]["pass_rule_checks_selected_but_vacuous"]),
            ", ".join(defects["summary"]["orphaned_defect_switches"]) or "none",
            ", ".join(defects["summary"]["mutations_witnessing_nothing"]) or "none")),
        # RW-19 — the D-B5 rule has no discriminating fixture; the self-test is the
        # only place it is shown load-bearing, so the gate depends on it.
        ("14 D-B5 degradation rule shown load-bearing (harness self-test)",
         bool(defects["summary"]["degradation_self_test_discriminates"]),
         "clean refuses citing degradation under an envelope that would otherwise "
         "authorize; seeded ignore_degradation emits the action"),
        # RW-27 — requirement 4's last uncompared dimension. The criterion is
        # coverage-honest, not count-maximising: it passes when every mapped
        # expectation is compared and agrees, and it PRINTS the unmapped and
        # unresolved counts so neither can hide inside a green line.
        ("15 expected.attention compared for every mapped fixture",
         base["summary"]["attention_compared"] > 0 and s["failures"] == 0,
         "%d/%d combinations compared, %d unmapped (expectation names no D-B7 §2.1 "
         "band), %s"
         % (base["summary"]["attention_compared"], s["combinations_computed"],
            base["summary"]["attention_unmapped"],
            ("%d UNRESOLVED, returned as change requests (%s)"
             % (base["summary"]["attention_unresolved"],
                ", ".join(base["summary"]["attention_unresolved_fixtures"])))
            if base["summary"]["attention_unresolved"]
            else "0 unresolved — the `27_` hub ruling closed S7 and A14")),
        # --- TASK-0004 / P2T corrections ---------------------------------
        # P2U-01 — this criterion used to read `compared > 0` per dimension and print
        # the counts. Both were true while five receipt expectations were counted as
        # compared and compared nothing, which is why the count is no longer the
        # criterion: every classification must be accounted for (no combination may
        # fall outside the four buckets), and no mapped combination may have executed
        # zero comparisons.
        ("16 every expected dimension accounted for and actually compared",
         all(base["summary"]["dimension_coverage"][d]["accounted"]
             == s["combinations_computed"]
             and not base["summary"]["dimension_coverage"][d]["unaccounted"]
             and base["summary"]["dimension_coverage"][d]["mapped"] > 0
             and base["summary"]["dimension_coverage"][d][
                 "min_comparisons_when_mapped"] >= 1
             for d in ("route", "attention", "authority", "receipt"))
         and s["failures"] == 0,
         "; ".join(
             "%s %d compared / %d unmappable / %d not-simulated / %d n-a = %d"
             % (d, base["summary"]["dimension_coverage"][d]["mapped"],
                base["summary"]["dimension_coverage"][d]["unmappable"],
                base["summary"]["dimension_coverage"][d]["not_simulated"],
                base["summary"]["dimension_coverage"][d]["not_applicable"],
                base["summary"]["dimension_coverage"][d]["accounted"])
             for d in ("route", "attention", "authority", "receipt"))
         + "; every mapped combination executed >=%d comparison(s) (floor: %s fixtures)"
         % (min(base["summary"]["dimension_coverage"][d]["min_comparisons_when_mapped"]
                for d in ("route", "attention", "authority", "receipt")),
            base["summary"]["dimension_floor_fixtures"])),
        ("17 every verifier oracle probe defeated; dimensions load-bearing",
         omut["summary"]["verifier_probes_defeated"] == omut["summary"]["verifier_probes"]
         and omut["summary"]["presentation_probes_excluded"]
         == omut["summary"]["presentation_probes"]
         and not omut["summary"]["sentinel_survived"]
         and not omut["summary"]["sentinel_missing_rationale"]
         and not omut["summary"]["not_load_bearing"]
         and not omut["summary"]["same_kind_survived"]
         and not omut["summary"]["same_kind_stale_declarations"]
         and not omut["summary"]["missing_exclusion_rationale"]
         and bool(omut["summary"]["defect_witness_cases_failed"])
         and bool(omut["summary"]["defect_witness_section_d_detected"]),
         "%d/%d 28A_ probes defeated; %d/%d 32A_ presentation probes excluded from "
         "the compared set; %d/%d sentinel corruptions rejected (%d not rejectable, "
         "each with a recorded reason); %d/%d governed pairs have a contradictory "
         "witness; same-kind: %d witness / %d discriminating elsewhere / %d declared "
         "coarsened / %d no corpus alternative; P2U-01 defect witness caught by both "
         "guards"
         % (omut["summary"]["verifier_probes_defeated"],
            omut["summary"]["verifier_probes"],
            omut["summary"]["presentation_probes_excluded"],
            omut["summary"]["presentation_probes"],
            omut["summary"]["sentinel_rejected"], omut["summary"]["sentinel_pairs"],
            len(omut["summary"]["sentinel_not_rejectable"]),
            omut["summary"]["contradiction_load_bearing"],
            omut["summary"]["governed_pairs"],
            omut["summary"]["same_kind_with_witness"],
            omut["summary"]["same_kind_discriminating_elsewhere"],
            len(omut["summary"]["same_kind_value_blind"]),
            len(omut["summary"]["same_kind_no_alternative"]))),
        ("18 incomplete causal basis fails closed before any state is emitted",
         basis["summary"]["closed"] == basis["summary"]["cases"]
         and not basis["summary"]["production_basis_problems"],
         "%d/%d missing-basis cases fail closed (incl. the verifier's exact probe); "
         "%d production combinations validate clean"
         % (basis["summary"]["closed"], basis["summary"]["cases"],
            basis["summary"]["production_combinations_validated"])),
        # P2U-02 — a declared external basis is not a resolved one. Separate criterion
        # rather than folded into 18: the two failed for different reasons and a
        # single green line covering both is how the second one stayed open.
        ("18b every declared external basis resolves or the case fails closed",
         basis["summary"]["external_closed"] == basis["summary"]["external_cases"]
         and bool(basis["summary"]["external_positive_resolves"])
         and bool(basis["summary"]["digest_enumeration_guard_discriminates"])
         and bool(basis["summary"]["r1_contract_witnesses_all_witness"]),
         "%d/%d external-basis cases fail closed (the four P2U-02 probe strings; "
         "nonexistent object, wrong version/hash, omission from the frozen manifest, "
         "no manifest, degraded and unavailable resolver, tampered digest, "
         "unverified record, undeclared store; the P2V-02 receipt cases; and the "
         "R2 additions — receipt naming a manifest record, attesting to another "
         "subject, revoked, purposeless, abbreviated content hash, no registry, "
         "wrong/same authority, stale revocation snapshot, unbound registry, "
         "duplicate receipt ids, snapshot identity edited, and four envelope-control "
         "cases). %d were accepted by the prefix check TASK-0005 replaced. The "
         "resolvable reference folds under two distinct authorities; the four "
         "enumeration guards are shown failing; %d/%d `38A_` probes witness their "
         "finding under both contracts"
         % (basis["summary"]["external_closed"], basis["summary"]["external_cases"],
            basis["summary"]["external_accepted_by_the_prefix_check_this_replaces"],
            len(basis["r1_contract_witnesses"]["probes"])
            - len(basis["summary"]["r1_contract_witnesses_not_witnessing"]),
            len(basis["r1_contract_witnesses"]["probes"]))),
        ("19 P2S-04 schedule-liveness behaviors demonstrated (incl. the P2U-03, "
         "P2V-04 and P2W-04 probes)",
         sched["summary"]["discriminating"] == sched["summary"]["behaviors"],
         "%d/%d behaviors discriminate under their targeted defect "
         "(scheduler death before registration; horizon exhaustion; atomic "
         "versioned change inspecting the watchdog's own horizon state; the P2U-03 "
         "stale-horizon probe; the P2V-04 retired-version probe; and the six P2W-04 "
         "cases — same-version change, register-is-initial-only, monotonic identity, "
         "restart preserving retirement through the control-journal fold, concurrent "
         "changes, and replay determinism from the durable journal)"
         % (sched["summary"]["discriminating"], sched["summary"]["behaviors"])),
    ]

    print("=" * 86)
    print("TASK-0003 — P2S-01 Behavioral Candidate-Transition/Fold Simulator")
    print("=" * 86)
    print("fixtures %d x shapes %d (%s) = %d combinations"
          % (s["fixtures"], s["shapes"], ", ".join(SHAPES), s["combinations_expected"]))
    print()
    print("ACCEPTANCE CRITERIA")
    for label, ok, detail in criteria:
        print("  [%s] %-58s %s" % ("PASS" if ok else "FAIL", label, detail))

    print()
    print("EXERCISED through the real mechanism (run_composition.py)")
    print("  %s" % "; ".join(EXERCISED_BY_COMPOSITION_SUITE))
    print()
    print("ACCOUNTED ELSEWHERE (RW-23 — neither driven here nor unlisted)")
    for line in ACCOUNTED_ELSEWHERE:
        print("  - %s" % line)
    print()
    print("DECLARED NOT-SIMULATED (RW-09/RW-13 — these are NOT exercised)")
    for line in NOT_SIMULATED:
        print("  - %s" % line)

    all_ok = all(ok for _, ok, _ in criteria)
    payload = {
        "criteria": [{"criterion": c, "passed": bool(ok), "detail": d}
                     for c, ok, d in criteria],
        "all_passed": all_ok,
        "base_summary": s,
        "defects_summary": defects["summary"],
        "shuffle_summary": shuffle["summary"],
        "p2s05_summary": p2s05["summary"],
        "p2s07_summary": p2s07["summary"],
        "anticircularity_passed": anti_ok,
        "not_simulated": NOT_SIMULATED,
        "exercised_by_composition_suite": EXERCISED_BY_COMPOSITION_SUITE,
        "accounted_elsewhere": ACCOUNTED_ELSEWHERE,
        "composition_summary": comp["summary"],
        "oracle_mutation_summary": omut["summary"],
        "basis_summary": basis["summary"],
        "p2s04_summary": sched["summary"],
        "predicates_not_evaluable": sorted(not_evaluable),
    }
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "gate_report.json"), "w",
              encoding="utf-8", newline="\n") as fh:
        json.dump(payload, fh, indent=2, sort_keys=True, ensure_ascii=False)
        fh.write("\n")

    print()
    print("GATE %s" % ("PASS — all acceptance criteria met" if all_ok
                       else "FAIL — see criteria above"))
    print("outputs written to %s/" % args.out)
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
